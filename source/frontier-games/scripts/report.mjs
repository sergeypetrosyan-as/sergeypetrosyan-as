// Compiles docs/arcade-90/ROSTER.md (the working roster) from the concepts, the game files and the verification results.
// Usage: node scripts/report.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONCEPTS, CATEGORIES } from '../concepts.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(pkg, '../..');
const start = JSON.parse(readFileSync(resolve(repo, 'docs/arcade-90/starting-roster.json'), 'utf8'));
const rows = [];
let verified = 0, implemented = 0;
for (const c of CONCEPTS) {
  const hasGame = existsSync(resolve(pkg, `src/games/${c.id}.ts`)) && existsSync(resolve(pkg, `src/meta/${c.id}.mjs`));
  const vf = resolve(repo, `docs/arcade-90/verification/${c.id}.json`);
  const v = existsSync(vf) ? JSON.parse(readFileSync(vf, 'utf8')) : null;
  if (hasGame) implemented++;
  if (v?.ok) verified++;
  const motif = hasGame ? (await import(pathToFileURL(resolve(pkg, `src/meta/${c.id}.mjs`)).href)).default.motif : '';
  const cat = CATEGORIES.find((x) => x.id === c.category).name;
  rows.push(`| ${c.batch} | \`${c.id}\` | ${c.title} | ${cat} | ${c.does} | \`${c.route}\` | ${hasGame ? 'implemented' : 'todo'} | ${v ? (v.ok ? `pass (${v.checks.length} checks, ${v.base}, ${v.at.slice(0, 10)})` : 'FAIL') : 'not run'} | ${motif.replace(/\|/g, '/')} |`);
}
const md = `# Working roster: 90 new games

Generated by \`source/frontier-games/scripts/report.mjs\` from \`concepts.mjs\`, the game files and \`docs/arcade-90/verification/*.json\`.

- Starting roster (before this work): ${start.games.length} games, recorded in \`starting-roster.json\` (${start.games.map((g) => `\`${g.id}\``).join(', ')}).
- New games: ${CONCEPTS.length} unique ids. Implemented: ${implemented}. Verified: ${verified}.

| Batch | ID | Title | Kind | What the player does | Route | Status | Verification | Motif and its gameplay job |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(resolve(repo, 'docs/arcade-90/ROSTER.md'), md);
console.log(`roster: ${implemented}/${CONCEPTS.length} implemented, ${verified}/${CONCEPTS.length} verified`);
